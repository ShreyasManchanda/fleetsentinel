"""Ports (interfaces) between application services and I/O adapters. Rows are plain dicts shaped like the API models,
so the application layer stays framework-free and every port has an in-memory fake for unit tests."""
from __future__ import annotations

from contextlib import AbstractAsyncContextManager
from dataclasses import dataclass
from typing import Any, Protocol

Row = dict[str, Any]


class VehicleRepo(Protocol):
    async def list_page(self, *, fleet_id: str | None, min_risk: float | None, vin_prefix: str | None, sort: str,
                        after: list[Any] | None, limit: int) -> list[Row]: ...
    async def get(self, vin: str) -> Row | None: ...
    async def trips(self, vin: str, after: list[Any] | None, limit: int) -> list[Row] | None: ...
    async def recent_trips(self, vin: str, n: int) -> list[Row]: ...
    async def recent_alerts(self, vin: str, n: int) -> list[Row]: ...
    async def latest_risk(self, vin: str) -> Row | None: ...
    async def lookalikes(self, vin: str, k: int) -> list[Row] | None: ...
    async def fleet_summary(self, fleet_id: str | None, risk_threshold: float) -> Row: ...


class AlertRepo(Protocol):
    async def list_page(self, *, statuses: list[str] | None, severity: str | None, rule: str | None, vin: str | None,
                        since: str | None, after: list[Any] | None, limit: int) -> list[Row]: ...
    async def get(self, alert_id: str) -> Row | None: ...
    async def set_status(self, alert_id: str, status: str, reviewer_sub: str) -> Row | None: ...


class DriverRepo(Protocol):
    async def list_page(self, *, sort: str, fleet_id: str | None, after: list[Any] | None, limit: int) -> list[Row]: ...
    async def get(self, driver_id: str) -> Row | None: ...


class ActionRepo(Protocol):
    async def list_page(self, *, status: str | None, after: list[Any] | None, limit: int) -> list[Row]: ...
    async def create(self, *, proposal: dict, rationale: str, expected_impact_usd: float, alert_id: str | None,
                     idempotency_key: str) -> Row: ...
    async def get(self, action_id: str) -> Row | None: ...
    async def decide(self, action_id: str, status: str, reviewer_sub: str, reason: str | None) -> Row | None: ...


class MappingRepo(Protocol):
    async def list_all(self) -> list[Row]: ...
    async def next_version(self, oem: str) -> int | None: ...
    async def create_draft(self, oem: str, version: int, document: dict, created_by: str) -> Row | None: ...
    async def get(self, oem: str, version: int) -> Row | None: ...
    async def set_status(self, oem: str, version: int, status: str) -> Row: ...
    async def activate(self, oem: str, version: int) -> Row: ...
    async def active_versions(self) -> dict[str, int]: ...


class AuditRepo(Protocol):
    async def list_page(self, *, actor_id: str | None, action: str | None, decision: str | None,
                        after: list[Any] | None, limit: int) -> list[Row]: ...
    async def verify(self, from_seq: int, to_seq: int | None) -> Row: ...


class DsrRepo(Protocol):
    async def create(self, driver_id: str, kind: str) -> Row: ...
    async def get(self, dsr_id: str) -> Row | None: ...
    async def load_subject(self, driver_id: str) -> Row | None: ...
    async def destroy_key(self, subject_key_id: str) -> bool: ...
    async def read_key(self, subject_key_id: str) -> Row | None: ...
    async def null_pii(self, driver_id: str) -> int: ...
    async def pseudonymize_trips(self, driver_id: str) -> int: ...
    async def subject_export(self, driver_id: str) -> Row: ...
    async def finish(self, dsr_id: str, status: str, evidence: dict) -> Row: ...


class ReportRepo(Protocol):
    async def cost_report(self, date_from: str, date_to: str, group_by: str) -> Row: ...
    async def insight_rows(self, date_from: str, date_to: str) -> list[tuple[int, float, float, float, int]]: ...
    async def tenant_vins(self) -> list[str]: ...


@dataclass(slots=True)
class Repos:
    vehicles: VehicleRepo
    alerts: AlertRepo
    drivers: DriverRepo
    actions: ActionRepo
    mappings: MappingRepo
    audit: AuditRepo
    dsr: DsrRepo
    reports: ReportRepo
    reviewer_id: Any = None


class TenantDb(Protocol):
    """One request = one transaction with `SELECT set_config('app.tenant_id', :tenant, true)` executed FIRST."""

    def tx(self, tenant_id: str) -> AbstractAsyncContextManager[Repos]: ...
    async def ping(self) -> None: ...


# ---------------------------------------------------------------- non-relational stores
class StateStore(Protocol):
    """Latest vehicle state (Redis). Values: {lat, lon, status, ts_ms, ...}."""

    async def get_states(self, tenant_id: str, vins: list[str]) -> dict[str, Row]: ...
    async def viewport(self, tenant_id: str, west: float, south: float, east: float, north: float, limit: int
                       ) -> tuple[list[Row], bool]: ...
    async def status_counts(self, tenant_id: str) -> dict[str, int]: ...
    async def freshness_p95_ms(self) -> int: ...
    async def model_fallback_active(self) -> bool: ...
    async def is_flagged(self, tenant_id: str, vin: str) -> bool: ...
    async def flagged_set(self, tenant_id: str) -> set[str]: ...
    async def purge_driver(self, tenant_id: str, driver_id: str) -> int: ...
    async def ping(self) -> None: ...


class TwinStore(Protocol):
    async def get(self, tenant_id: str, vin: str) -> Row | None: ...
    async def purge_driver(self, tenant_id: str, driver_id: str) -> int: ...
    async def ping(self) -> None: ...


class AlertFeed(Protocol):
    """Live alert push source (Redis pub/sub in prod)."""

    def subscribe(self, tenant_id: str): ...  # async context manager yielding an object with `async get(timeout)`


class MappingPublisher(Protocol):
    async def publish(self, oem: str, document: dict) -> None: ...


class AgentClient(Protocol):
    async def chat(self, bearer: str, tenant_id: str, message: str, conversation_id: str | None) -> Row: ...
    async def briefing(self, bearer: str, tenant_id: str, generate: bool) -> Row: ...


class ReportRunner(Protocol):
    async def run(self, report_id: str, params: dict, vins: list[str]) -> Row: ...


class QualityStore(Protocol):
    async def oem_quality(self) -> list[Row]: ...
    async def dlq_sample(self, oem: str | None, reason: str | None, limit: int) -> list[Row]: ...
    async def replay_dlq(self, oem: str, reason: str | None, limit: int | None) -> Row: ...


class IdempotencyStore(Protocol):
    async def begin(self, scope: str, fingerprint: str, ttl_s: int) -> tuple[str, Row | None]:
        """-> ('new', None) | ('replay', stored_record) | ('in_flight', None) | ('mismatch', None)"""
        ...

    async def complete(self, scope: str, record: Row, ttl_s: int) -> None: ...
    async def abort(self, scope: str) -> None: ...


class AgentUnavailable(Exception):
    """The copilot service is down, returned a non-2xx, or has no LLM key: the platform continues without it."""
