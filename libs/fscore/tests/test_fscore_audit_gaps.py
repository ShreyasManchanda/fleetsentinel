def test_topk_equal_estimate_keeps_incumbent_and_ties_break_by_item():
    tk = TopK(2, CountMinSketch(512, 3))
    for _ in range(20):
        tk.update("B")
        tk.update("A")
    tk.update("C")  # estimate 1 == min? no: min is 20; C(1) must NOT evict
    assert sorted(n for n, _ in tk.top()) == ["A", "B"]
    names = [n for n, e in tk.top() if e == tk.top()[0][1]]
    assert names == sorted(names)


def test_topk_restore_then_update_stays_bounded_and_correct():
    tk = TopK(2, CountMinSketch(512, 3))
    for x in ["A"] * 10 + ["B"] * 5:
        tk.update(x)
    tk2 = TopK(2, CountMinSketch(512, 3))
    tk2.cms = tk.cms
    tk2.restore_items(tk.snapshot())
    for _ in range(10):
        tk2.update("C")
    assert len(tk2._heap) <= 8 * tk2.k + 64 + 2
    assert {n for n, _ in tk2.top()} == {"A", "C"}


