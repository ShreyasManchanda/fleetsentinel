@settings(deadline=None, max_examples=30)
@given(st.integers(0, 1_000_000))
def test_hll_union_estimate_close_to_truth(seed):
    import random
    rng = random.Random(seed)
    a_items = [f"a{i}" for i in rng.sample(range(5000), 600)]
    b_items = [f"b{i}" for i in rng.sample(range(5000), 600)]
    ha, hb = HyperLogLog(10), HyperLogLog(10)
    for x in a_items:
        ha.add(x)
    for x in b_items:
        hb.add(x)
    ha.merge(hb)
    union = len(set(a_items) | set(b_items))
    assert abs(ha.count() - union) / union < 0.2
    ha.merge(ha)  # merging with self is a no-op for the estimate
    assert abs(ha.count() - union) / union < 0.2


