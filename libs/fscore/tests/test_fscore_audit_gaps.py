def _murmur2_reference(data: bytes) -> int:
    """Independent straight-line port of Kafka's murmur2 (byte-wise, no numpy)."""
    m = 0x5BD1E995
    h = (0x9747B28C ^ len(data)) & 0xFFFFFFFF
    i = 0
    while i + 4 <= len(data):
        k = data[i] | (data[i + 1] << 8) | (data[i + 2] << 16) | (data[i + 3] << 24)
        k = (k * m) & 0xFFFFFFFF
        k ^= k >> 24
        k = (k * m) & 0xFFFFFFFF
        h = (h * m) & 0xFFFFFFFF
        h ^= k
        i += 4
    rem = len(data) - i
    if rem == 3:
        h ^= data[i + 2] << 16
    if rem >= 2:
        h ^= data[i + 1] << 8
    if rem >= 1:
        h ^= data[i]
        h = (h * m) & 0xFFFFFFFF
    h ^= h >> 13
    h = (h * m) & 0xFFFFFFFF
    h ^= h >> 15
    return h


@settings(deadline=None, max_examples=120)
@given(st.binary(min_size=0, max_size=41))
def test_murmur2_matches_reference_on_all_remainder_branches(data):
    # Lengths mod 4 hit the rem == 0/1/2/3 paths; empty input hits the seed-only path.
    assert hashing.murmur2(data) == _murmur2_reference(data)


