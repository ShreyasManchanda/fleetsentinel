def _doc(extra):
    base = {"oem": "T", "version": 1, "envelope": {"records": "$.rs[*]"},
            "fields": {"vin": {"path": "$.v", "transform": ["validate_vin"]},
                       "ts_ms": {"path": "$.t", "transform": ["to_int"]},
                       "lat": {"path": "$.la", "transform": ["to_float"]},
                       "lon": {"path": "$.lo", "transform": ["to_float"]}}}
    out = copy.deepcopy(base)
    out["fields"].update(extra)
    return out


def _good(**kw):
    r = {"v": "1HGCM82633A004352", "t": 1_790_590_500_000, "la": 12.9, "lo": 77.6}
    r.update(kw)
    return r


