# ---------------------------------------------------------------- anti-replay
def test_window_exact_boundary_and_seq_zero():
    w = AntiReplayWindow()
    assert w.check_and_update(0) is Verdict.NEW  # stream starting at zero
    assert w.check_and_update(100) is Verdict.NEW
    assert w.check_and_update(100 - (WINDOW - 1)) is Verdict.NEW   # oldest slot still inside
    assert w.check_and_update(100 - WINDOW) is Verdict.TOO_OLD    # one older => outside
    assert w.seen(100 - (WINDOW - 1)) is True and w.seen(100 - WINDOW) is None


def test_window_init_masks_bitmap():
    w = AntiReplayWindow(max_seq=10, bitmap=(1 << 200) | 0b11)
    assert w.bitmap.bit_length() <= WINDOW
    assert w.check_and_update(10) is Verdict.DUPLICATE and w.check_and_update(9) is Verdict.DUPLICATE


def test_store_snapshot_restore_multi_key_isolation():
    s = AntiReplayStore()
    s.check_and_update("A", 10)
    s.check_and_update("B", 3)
    s2 = AntiReplayStore.restore({k: list(v) for k, v in s.snapshot().items()})
    assert s2.check_and_update("A", 10) is Verdict.DUPLICATE
    assert s2.check_and_update("B", 3) is Verdict.DUPLICATE
    assert s2.check_and_update("A", 11) is Verdict.NEW
    assert s2.check_and_update("B", 4) is Verdict.NEW


