def test_cancel_pending_before_start():
    w = TimingWheel(tick_ms=1000)
    w.schedule("p", 60_000)
    assert w.cancel("p") is True and "p" not in w and w.deadline("p") is None
    assert w.advance(120_000) == [] and len(w) == 0


def test_reschedule_before_start_replaces():
    w = TimingWheel(tick_ms=1000)
    w.schedule("a", 60_000)
    w.schedule("a", 30_000)
    assert len(w) == 1 and w.deadline("a") == 30_000
    assert w.advance(0) == []  # clock starts; nothing due yet
    assert w.advance(30_000) == [("a", 30_000)]


def test_advance_backwards_never_fires_and_keeps_entries():
    w = TimingWheel(tick_ms=1000)
    w.schedule("a", 50_000)
    assert w.advance(40_000) == []
    assert w.advance(30_000) == []  # backwards: no fire, no loss
    assert w.advance(50_000) == [("a", 50_000)]


def test_negative_deadline_fires_on_first_advance():
    w = TimingWheel(tick_ms=1000)
