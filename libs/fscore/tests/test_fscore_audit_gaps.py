def test_store_ttl_boundary_inclusive_then_expiry():
    now = [0.0]
    lw = c.LocalDevWrapper()
    store = c.SubjectKeyStore(lw, max_size=8, ttl_s=10, clock=lambda: now[0])
    dek = c.generate_dek()
    wrapped = lw.wrap(dek)
    assert store.dek("a", wrapped) == dek
    now[0] = 10.0
    assert store.dek("a", wrapped) == dek and store.unwraps == 1  # exactly ttl => still a hit
    now[0] = 10.0001
    assert store.dek("a", wrapped) == dek and store.unwraps == 2


def test_store_rotated_wrapped_dek_reunwraps():
    lw = c.LocalDevWrapper()
    store = c.SubjectKeyStore(lw)
